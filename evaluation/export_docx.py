"""
Export evaluation results to Word document business plan.
"""

import json
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, List

from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH


def _extract_readable_text(item: Any) -> str:
    """
    Extract readable text from a dict, list, or string.

    For dicts: tries common field names in order of preference.
    For lists: joins items.
    For strings: returns as-is.
    """
    if isinstance(item, dict):
        # Try common field names for readable content
        for field in ["statement", "uncertainty", "item", "description", "text", "content"]:
            if field in item and item[field]:
                return str(item[field])

        # If no common field found, format as key-value pairs
        # but skip internal/technical fields
        skip_keys = {"id", "because", "evidence_quality", "section_number", "confidence"}
        readable_parts = []
        for k, v in item.items():
            if k not in skip_keys and v:
                readable_parts.append(f"{k.replace('_', ' ')}: {v}")

        if readable_parts:
            return "; ".join(readable_parts)

        # Last resort: convert whole dict
        return str(item)

    elif isinstance(item, list):
        return ", ".join([_extract_readable_text(i) for i in item])

    else:
        return str(item)


# Section metadata mapping
SECTION_NAMES = {
    "1": "Opportunity Analysis",
    "3": "Environment Research",
    "4": "Organisation Design",
    "5": "SWOT Synthesis",
    "8": "Marketing Strategy",
    "10": "Operations",
    "12": "Financial Modelling",
    "13": "Launch & Contingency",
    "executive_summary": "Executive Summary",
}


def export_to_docx(results_path: str) -> str:
    """
    Export grounded eval results to a Word document business plan.

    Args:
        results_path: Path to the results JSON file

    Returns:
        Full path to the saved .docx file
    """
    # Read results
    with open(results_path) as f:
        data = json.load(f)

    # Create outputs directory
    outputs_dir = Path("outputs")
    outputs_dir.mkdir(exist_ok=True)

    # Generate filename
    idea_name = data.get("idea_name", "business_plan").replace(" ", "_")
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"business_plan_{idea_name}_{timestamp}.docx"
    output_path = outputs_dir / filename

    # Create document
    doc = Document()

    # Build the document
    _add_cover_page(doc, data)
    _add_executive_summary(doc, data)
    _add_agent_sections(doc, data)
    _add_gaps_page(doc, data)

    # Save
    doc.save(str(output_path))
    return str(output_path)


def _add_cover_page(doc: Document, data: Dict[str, Any]):
    """Add cover page with title and metadata."""
    # Title
    title = doc.add_heading(data.get("idea_name", "Business Plan"), level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Subtitle
    subtitle = doc.add_paragraph("Business Plan")
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle.runs[0].font.size = Pt(16)
    subtitle.runs[0].font.italic = True

    doc.add_paragraph()  # spacing

    # Date
    date_para = doc.add_paragraph(
        f"Generated: {datetime.now().strftime('%B %d, %Y')}"
    )
    date_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Confidence note
    doc.add_paragraph()
    doc.add_paragraph()
    note = doc.add_paragraph(
        "This business plan was generated by a multi-agent AI system. "
        "All assumptions, uncertainties, and confidence levels are explicitly "
        "stated throughout the document. Gaps in available data are flagged "
        "at the end."
    )
    note.alignment = WD_ALIGN_PARAGRAPH.CENTER
    note.runs[0].font.italic = True
    note.runs[0].font.size = Pt(10)

    # Metadata
    doc.add_paragraph()
    doc.add_paragraph()
    metadata = doc.add_paragraph()
    metadata.alignment = WD_ALIGN_PARAGRAPH.CENTER
    metadata.add_run(f"Total tokens: {data.get('total_input_tokens', 0) + data.get('total_output_tokens', 0):,}\n")
    metadata.add_run(f"Processing time: {data.get('total_latency_seconds', 0):.1f}s\n")
    metadata.add_run(f"Grounded with CEO data: {'Yes' if data.get('grounded') else 'No'}")

    doc.add_page_break()


def _add_executive_summary(doc: Document, data: Dict[str, Any]):
    """Add executive summary section."""
    doc.add_heading("Executive Summary", level=1)

    sections = data.get("sections", {})
    exec_section = sections.get("executive_summary", {})
    output = exec_section.get("output", {})

    if not output:
        doc.add_paragraph("Executive summary not available.")
        doc.add_page_break()
        return

    # Main content
    summary_text = output.get("executive_summary", "")
    if summary_text:
        doc.add_paragraph(summary_text)
    else:
        doc.add_paragraph("No executive summary generated.")

    # Confidence
    confidence = output.get("confidence_score", "unknown")
    conf_para = doc.add_paragraph()
    conf_para.add_run("Confidence: ").bold = True
    conf_para.add_run(str(confidence))

    # Key metrics if available
    key_metrics = output.get("key_metrics", [])
    if key_metrics:
        doc.add_heading("Key Metrics", level=3)
        for metric in key_metrics:
            doc.add_paragraph(_extract_readable_text(metric), style="List Bullet")

    # Uncertainties
    uncertainties = output.get("uncertainties", [])
    if uncertainties:
        doc.add_heading("Uncertainties", level=3)
        for unc in uncertainties:
            # Extract main text from dict or use as-is if string
            if isinstance(unc, dict):
                text = _extract_readable_text(unc)
                severity = unc.get("severity", "")
                if severity:
                    text = f"{text} [{severity}]"
            else:
                text = str(unc)

            p = doc.add_paragraph(text, style="List Bullet")
            p.runs[0].font.italic = True

    doc.add_page_break()


def _add_agent_sections(doc: Document, data: Dict[str, Any]):
    """Add all agent output sections."""
    sections = data.get("sections", {})
    section_order = ["1", "3", "4", "5", "8", "10", "12", "13"]

    for section_num in section_order:
        section_data = sections.get(section_num)
        if not section_data:
            continue

        section_name = SECTION_NAMES.get(section_num, f"Section {section_num}")
        doc.add_heading(f"{section_num}. {section_name}", level=1)

        output = section_data.get("output", {})
        if not output:
            doc.add_paragraph("Section not available.")
            doc.add_page_break()
            continue

        # Add main content fields
        _add_section_content(doc, output, section_num)

        # Confidence
        confidence = output.get("confidence_score", "unknown")
        conf_para = doc.add_paragraph()
        conf_para.add_run("Confidence Level: ").bold = True
        run = conf_para.add_run(str(confidence))
        if str(confidence).lower() in ["low", "medium-low"]:
            run.font.color.rgb = RGBColor(255, 140, 0)  # orange

        # Assumptions
        assumptions = output.get("assumptions_used", [])
        if assumptions:
            doc.add_heading("Assumptions", level=3)
            for assumption in assumptions:
                # Extract main statement from dict or use as-is if string
                if isinstance(assumption, dict):
                    statement = assumption.get("statement", _extract_readable_text(assumption))
                    p = doc.add_paragraph(statement, style="List Bullet")

                    # Add metadata as italic below if available
                    confidence = assumption.get("confidence", "")
                    source = assumption.get("source", "")
                    if confidence or source:
                        meta_parts = []
                        if confidence:
                            meta_parts.append(f"confidence: {confidence}")
                        if source:
                            meta_parts.append(f"source: {source}")
                        meta_para = doc.add_paragraph("  " + " | ".join(meta_parts), style="List Bullet")
                        meta_para.runs[0].font.italic = True
                        meta_para.runs[0].font.size = Pt(9)
                else:
                    p = doc.add_paragraph(str(assumption), style="List Bullet")

                # Bold ASSUMPTION tags
                if p.text and "ASSUMPTION" in p.text.upper():
                    p.runs[0].bold = True

        # Uncertainties
        uncertainties = output.get("uncertainties", [])
        if uncertainties:
            doc.add_heading("Uncertainties", level=3)
            for unc in uncertainties:
                # Extract main text from dict or use as-is if string
                if isinstance(unc, dict):
                    text = _extract_readable_text(unc)
                    severity = unc.get("severity", "")
                    if severity:
                        text = f"{text} [{severity}]"
                else:
                    text = str(unc)

                p = doc.add_paragraph(text, style="List Bullet")
                p.runs[0].font.italic = True

        # Unresolved challenges
        challenges = output.get("_unresolved_challenges", [])
        if challenges:
            doc.add_heading("Unresolved Challenges", level=3)
            for challenge in challenges:
                text = _extract_readable_text(challenge)
                p = doc.add_paragraph(text, style="List Bullet")
                p.runs[0].font.color.rgb = RGBColor(255, 0, 0)  # red

        doc.add_page_break()


def _add_section_content(doc: Document, output: Dict[str, Any], section_num: str):
    """Add the main content fields for a section."""
    # Skip metadata fields
    skip_fields = {
        "section_number",
        "confidence_score",
        "assumptions_used",
        "uncertainties",
        "_unresolved_challenges",
        "input_tokens",
        "output_tokens",
    }

    for key, value in output.items():
        if key in skip_fields:
            continue

        # Format field name
        field_name = key.replace("_", " ").title()
        doc.add_heading(field_name, level=3)

        # Handle different value types
        if isinstance(value, list):
            for item in value:
                if isinstance(item, dict):
                    # Extract readable text from dict
                    text = _extract_readable_text(item)
                    doc.add_paragraph(text, style="List Bullet")
                else:
                    doc.add_paragraph(str(item), style="List Bullet")
        elif isinstance(value, dict):
            # For dict values, show as key: value pairs
            for k, v in value.items():
                skip_keys = {"id", "because", "evidence_quality"}
                if k not in skip_keys:
                    p = doc.add_paragraph()
                    p.add_run(f"{k.replace('_', ' ').title()}: ").bold = True
                    p.add_run(str(v))
        else:
            doc.add_paragraph(str(value))


def _add_gaps_page(doc: Document, data: Dict[str, Any]):
    """Add final page listing all gaps and uncertainties."""
    doc.add_heading("Data Gaps & Knowledge Limitations", level=1)

    doc.add_paragraph(
        "This section aggregates all uncertainties and unresolved challenges "
        "identified during the business plan generation. Addressing these gaps "
        "would improve the plan's accuracy and confidence."
    )

    sections = data.get("sections", {})
    all_uncertainties = []
    all_challenges = []

    for section_num, section_data in sections.items():
        output = section_data.get("output", {})
        section_name = SECTION_NAMES.get(section_num, f"Section {section_num}")

        uncertainties = output.get("uncertainties", [])
        for unc in uncertainties:
            all_uncertainties.append((section_name, unc))

        challenges = output.get("_unresolved_challenges", [])
        for challenge in challenges:
            all_challenges.append((section_name, challenge))

    # List uncertainties
    if all_uncertainties:
        doc.add_heading("Uncertainties", level=2)
        for section_name, unc in all_uncertainties:
            p = doc.add_paragraph()
            p.add_run(f"[{section_name}] ").bold = True

            # Extract readable text from dict or use as-is
            if isinstance(unc, dict):
                text = _extract_readable_text(unc)
                severity = unc.get("severity", "")
                if severity:
                    text = f"{text} [{severity}]"
            else:
                text = str(unc)

            p.add_run(text)

    # List unresolved challenges
    if all_challenges:
        doc.add_heading("Unresolved Challenges", level=2)
        for section_name, challenge in all_challenges:
            p = doc.add_paragraph()
            p.add_run(f"[{section_name}] ").bold = True

            text = _extract_readable_text(challenge)
            run = p.add_run(text)
            run.font.color.rgb = RGBColor(255, 0, 0)

    # Recommendation
    doc.add_paragraph()
    rec = doc.add_paragraph(
        "Recommendation: Address high-priority gaps through targeted research "
        "using the databases suggested in the data declaration message "
        "(Passport, GlobalData, Statista, CB Insights, etc.)."
    )
    rec.runs[0].font.italic = True
